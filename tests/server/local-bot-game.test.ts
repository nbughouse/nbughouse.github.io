import assert from "node:assert/strict";
import test from "node:test";
import type { Socket } from "socket.io-client";
import { GameConnection } from "../../public/src/game-connection";
import { openLocalBotGame } from "../../public/src/local-bot-game";
import { Color } from "../../shared/src/chess";
import { Player } from "../../shared/src/player";
import { Room, RoomStatus } from "../../shared/src/room";

test("solo setup, moves, bot confirmations and resignation work without any socket sends", async t => {
    let sends = 0;
    const connection = new GameConnection({ on: () => {}, emit: () => sends++ } as unknown as Socket);
    const onlinePlayer = new Player("online", "Me");
    const session = { game: connection, player: onlinePlayer as Player | undefined,
        onlinePlayer: undefined as Player | undefined, name: "Me" };
    let replica!: Room;
    connection.on("joined-room", raw => { replica = Room.deserialize(raw); });
    connection.on("bot-room-updated", raw => { replica = Room.deserialize(raw); });
    connection.on("started-room", (raw, now) => {
        replica.setGame(raw);
        replica.status = RoomStatus.PLAYING;
        replica.revision = 0;
        for (const match of replica.game.matches) match.lastMoveTime = now;
    });
    connection.on("p-moved-board", (board, move, now) => {
        replica.game.doMove(board, move, now);
        replica.revision++;
    });
    connection.on("ended-room", winner => replica.endRoom(winner));
    openLocalBotGame(session, { boards: 3, level: 5 });
    t.after(() => connection.closeLocal());
    assert.equal(replica.kind, "bot");
    assert.equal(replica.game.config.pocketShare, "none");
    connection.send("update-bot-settings", { matchNum: 2, timeBase: 300, initialBoard: "duck" }, 9, 2);
    await Promise.resolve();
    assert.equal(replica.game.matches.length, 2);
    assert.equal(replica.game.config.timeBase, 300);
    assert.equal(replica.game.config.initialBoard, "default");
    assert.equal(replica.botLevel, 9);
    assert.equal(replica.botSpeed, 2);
    connection.send("assign-player-board", onlinePlayer.id, 1, Color.WHITE);
    connection.send("join-board", 0, Color.BLACK);
    await Promise.resolve();
    assert.equal(replica.game.matches[1].whitePlayer?.isBot, true);
    assert.equal(replica.game.matches[0].blackPlayer?.isBot, true);
    connection.send("assign-player-board", onlinePlayer.id, 1, Color.BLACK);
    await Promise.resolve();
    assert.equal(replica.game.matches[1].blackPlayer?.id, onlinePlayer.id);
    assert.equal(replica.game.matches[0].whitePlayer?.id, onlinePlayer.id);
    connection.send("start-room");
    await Promise.resolve();
    assert.equal(replica.status, RoomStatus.PLAYING);
    connection.send("update-bot-settings", { matchNum: 3, timeBase: 60 }, 1);
    await Promise.resolve();
    assert.equal(replica.game.matches.length, 2);
    assert.equal(replica.botLevel, 9);
    const move = { from: { loc: "board", row: 6, col: 4 }, to: { loc: "board", row: 4, col: 4 } };
    connection.send("move-board", 0, Color.WHITE, move);
    await Promise.resolve();
    connection.send("bot-move", 1, Color.WHITE, move, 1);
    await Promise.resolve();
    assert.equal(replica.revision, 2);
    assert.equal(replica.game.matches[1].chess.turn, Color.BLACK);
    connection.send("resign-room");
    await Promise.resolve();
    assert.equal(replica.status, RoomStatus.LOBBY);
    assert.equal(sends, 0);
    connection.closeLocal();
    assert.equal(session.player, onlinePlayer);
});
